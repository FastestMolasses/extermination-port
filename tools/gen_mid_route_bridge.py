#!/usr/bin/env python3
"""Generate src/game/em_mid_route_bridge.inc: typed hook adapters into the
shared area runtime (em_area01_runtime_call) for the standalone level
ports the middle of the route binds (em_area04_port.h's EmArea04PortHooks,
em_area06_port.h's EmArea06PortHooks, em_area22_port.h's EmArea22PortHooks).

Each hook re-enters em_area01_runtime_call by its original address with
the argument registers in the hook's parameter order: integer parameters
in a0.. (sign-extended as the EE's 32-bit values are), float parameters in
f12.. (their bits); a result pointer receives v0 (int32_t / uint32_t /
uint64_t) or f0 (float). The ports' reference tests check each hook's
register map against the original instructions; the adapters own no
state and no behaviour (as em_area02_runtime_overlay.inc's).

Usage (port root): python3 tools/gen_mid_route_bridge.py   (rewrites the .inc)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/game/em_mid_route_bridge.inc'
SOURCES = (('src/game/em_area22_port.h', 'EmArea22PortHooks', 'm22'),
           ('src/game/em_area04_port.h', 'EmArea04PortHooks', 'm04'),
           ('src/game/em_area06_port.h', 'EmArea06PortHooks', 'm06'),
           ('src/game/em_level8_port.h', 'EmLevel8PortHooks', 'm08'))
HOOK = re.compile(r'int \(\*w_([0-9A-F]{8}|callback)\)\(void \*ctx(?:, )?([^)]*)\);')


def hooks(text, struct):
    end = text.index('} ' + struct + ';')
    body = text[text.rindex('typedef struct {', 0, end):end]
    out = []
    for m in HOOK.finditer(body):
        params = [p.strip() for p in m.group(2).split(',') if p.strip()]
        out.append((m.group(1), params))
    return out


def adapter(prefix, name, params):
    sig, ints, floats, result = ['void *ctx'], [], [], None
    for p in params:
        typ, var = p.rsplit(' ', 1)
        if var.startswith('*'):
            assert var == '*result' and result is None, (name, p)
            result = typ
            sig.append(f'{typ} *result')
        elif typ == 'float':
            floats.append(var)
            sig.append(p)
        else:
            assert typ in ('uint32_t', 'int32_t', 'uint64_t'), (name, p)
            ints.append((typ, var))
            sig.append(p)
    fn = 'c.a[0]' if name == 'callback' else None
    lines = [f'static int {prefix}_w_{name}({", ".join(sig)})', '{', '    EmArea01Runtime *r = ctx;']
    if name == 'callback':
        assert [t for t, _ in ints] == ['uint32_t', 'uint32_t'] and not floats and not result, params
        lines.append(f'    EmArea01Call c = {{.function = {ints[0][1]}, .sp = r->sp, .na = 1, .nf = 0}};')
        lines.append(f'    c.a[0] = (uint64_t)(int64_t)(int32_t){ints[1][1]};')
    else:
        lines.append(f'    EmArea01Call c = {{.function = 0x{name}u, .sp = r->sp, .na = {len(ints)}, '
                     f'.nf = {len(floats)}}};')
        for i, (typ, var) in enumerate(ints):
            cast = {'uint32_t': '(uint64_t)(int64_t)(int32_t)', 'int32_t': '(uint64_t)(int64_t)',
                    'uint64_t': ''}[typ]
            lines.append(f'    c.a[{i}] = {cast}{var};')
        for i, var in enumerate(floats):
            lines.append(f'    c.f[{i}] = em_ee_bits({var});')
    lines.append('    int rc = em_area01_runtime_call(r, &c);')
    if result:
        value = {'int32_t': '(int32_t)c.v0', 'uint32_t': '(uint32_t)c.v0', 'uint64_t': 'c.v0',
                 'float': 'em_ee_float(c.f0)'}[result]
        lines.append(f'    if (rc == 0 && result) *result = {value};')
    lines += ['    return rc;', '}', '']
    del fn
    return '\n'.join(lines)


def main():
    out = ['/* Generated by tools/gen_mid_route_bridge.py: typed hook adapters into',
           ' * the shared area runtime for the middle of the route (see the tool).',
           ' * Do not edit by hand. */', '']
    for path, struct, prefix in SOURCES:
        text = (ROOT / path).read_text()
        hs = hooks(text, struct)
        assert hs, struct
        for name, params in hs:
            out.append(adapter(prefix, name, params))
        out.append(f'static uint8_t *{prefix}_view(void *ctx, uint32_t address, uint32_t size)')
        out.append('{\n    return bytes(ctx, address, size, 0);\n}\n')
        out.append(f'static inline void {prefix}_hooks(EmArea01Runtime *r, {struct} *h)')
        out.append('{')
        out.append('    memset(h, 0, sizeof *h);')
        out.append('    h->ctx = r;')
        out.append(f'    h->bytes = {prefix}_view;')
        for name, _ in hs:
            out.append(f'    h->w_{name} = {prefix}_w_{name};')
        out.append('}\n')
    OUT.write_text('\n'.join(out))
    print(f'{OUT.relative_to(ROOT)}: {sum(len(hooks((ROOT / p).read_text(), s)) for p, s, _ in SOURCES)} adapters')
    return 0


if __name__ == '__main__':
    sys.exit(main())
